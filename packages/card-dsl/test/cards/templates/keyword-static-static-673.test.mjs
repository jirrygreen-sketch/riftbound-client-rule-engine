/** The shipped program, kept verbatim: only the harness gate is lifted. */
function probeView(canonicalCardId) {
  const published = publishedById.get(canonicalCardId);
  assert.ok(published, `generated card program ${canonicalCardId} is present`);
  return published.status === "executable" ? published : { ...published, status: "executable", judgeReason: undefined };
}

/** Bind every expanded static ability through the production engine binder. */
function bindStatics(program, sourceKeywords = []) {
  const binding = createProgramBinding({ cardPrograms: [program] });
  const { engine, kernel } = fixture({ cards: [{ id: "unit", cardId: program.canonicalCardId, types: ["unit"], might: 4 }] });
  engine.commit({ type: "move-zone", object: kernel.ref("unit"), to: "battlefield", location: BF });
  const source = { ...kernel.getObject("unit"), keywords: sourceKeywords };
  const abilities = binding.inspect(source).abilities;
  const outcomes = [];
  const binder = createEngineStaticBinder(engine);
  for (const ability of abilities) {
    if (ability.kind !== "static") continue;
    try {
      const handle = bindStaticAbility(binder, ability, source);
      handle.unbind();
      outcomes.push({ kind: ability.effect.kind, registered: true });
    } catch (error) {
      assert.ok(error instanceof ProgramBindingError, `${ability.effect.kind} must fail closed with ProgramBindingError`);
      assert.equal(error.code, "judge-required");
      outcomes.push({ kind: ability.effect.kind, message: error.message });
    }
  }
  return outcomes;
}

/** Expand the program's keywords and try to register their triggers for real. */
function triggerOutcome(program) {
  const binding = createProgramBinding({ cardPrograms: [program] });
  const { engine, kernel } = fixture({ cards: [{ id: "unit", cardId: program.canonicalCardId, types: ["unit"], might: 6 }] });
  engine.commit({ type: "move-zone", object: kernel.ref("unit"), to: "battlefield", location: BF });
  const source = kernel.getObject("unit");
  const translations = triggerRegistrations(binding.registry, source);
  try {
    registerProgramTriggers(binding.registry, engine, source);
    return { translations, registered: true };
  } catch (error) {
    return { translations, registered: false, error };
  }
}

function assertOutcome(outcomes, expected) {
  assert.deepEqual(outcomes.map(outcome => outcome.kind), expected.map(entry => entry.kind));
  for (const [index, want] of expected.entries()) {
    if (want.error !== undefined) assert.match(outcomes[index].message ?? "", want.error);
    else assert.equal(outcomes[index].registered, true, `${want.kind} must register`);
  }
}

