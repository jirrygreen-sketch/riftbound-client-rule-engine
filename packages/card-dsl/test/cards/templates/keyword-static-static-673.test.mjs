function assertDeclared(row) {
  const published = publishedById.get(row.canonicalCardId);
  assert.ok(published, `generated card program ${row.canonicalCardId} is present`);
  const expected = rows.find(entry => entry.canonicalCardId === row.canonicalCardId);
  if (published.status === "executable") {
    // Promotion path: the row already carries the real execution evidence, so
    // a promoted card must simply drop its judgeReason.
    assert.equal(published.judgeReason, undefined, `${row.name}: promoted cards drop judgeReason`);
    return;
  }
  assert.equal(published.status, "judge-required", `${row.name}: RIFT-673 does not promote these programs`);
  assert.ok(published.judgeReason?.trim(), `${row.name}: judge-required keeps a concrete reason`);
  expected?.declared?.(published.judgeReason);
}

function assertRowEvidence(row, golden) {
  if (row.expectedFailure) {
    // The merged engine rejects the play with the named cost/target error; it
    // never resolves the card with an invented payment or target.
    assert.throws(golden.run, row.expectedFailure, `${row.name}: expected fail-closed rejection`);
    return;
  }
  golden.run();
}

